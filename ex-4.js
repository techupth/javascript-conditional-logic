// Switch Statement
let lightBulbStatus = "On";

//Start coding here
switch (lightBulbStatus){
    case "On":
        console.log("Light bulb is On.");

    case "Off" :
        console.log("Light bulb is Off.");
    
    default:
        console.log("Please choose the correct input (On/Off)");
    
}

console.log(lightBulbStatus);